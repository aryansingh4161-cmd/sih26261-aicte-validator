"""Convert Saanvi's Drive sheet area_norms (downloaded as CSV) into config/area_norms.yaml for the area_min rule.
  python -m tools.norms_to_yaml config/area_norms.csv config/area_norms.yaml
Columns: room_type, min_rooms_rule_as_printed, min_rooms_number, min_area_per_room_sqm, programme, clause_as_printed, page, checked.
Only rows with checked = ok are used; they get clause_verified: true (a human read them in the Handbook). OWNER: Aryan."""
from __future__ import annotations

import argparse
import csv
import re

import yaml


def _num(v: str):
    v = (v or "").strip().replace(",", "")
    try:
        f = float(v)
    except ValueError:
        return None
    return int(f) if f.is_integer() else f


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", (s or "").strip().lower()).strip("_")


def convert(csv_path: str) -> dict:
    norms, skipped = [], 0
    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            row = {k.strip().lower(): (v or "").strip() for k, v in row.items() if k}
            if row.get("checked", "").lower() != "ok" or not row.get("room_type"):
                skipped += 1
                continue
            norms.append({"room_type": slug(row["room_type"]), "programme": row.get("programme", ""),
                          "min_rooms_rule_as_printed": row.get("min_rooms_rule_as_printed", ""),
                          "min_rooms_number": _num(row.get("min_rooms_number", "")),
                          "min_area_per_room_sqm": _num(row.get("min_area_per_room_sqm", "")),
                          "aph_clause": row.get("clause_as_printed", ""), "page": row.get("page", ""), "clause_verified": True})
    return {"source": f"{csv_path} (rows with checked = ok)", "placeholder": False,
            "example": "min_rooms_number = UG Engineering, 1 division of 60 per year, 4 years", "skipped_rows": skipped, "norms": norms}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", nargs="?", default="config/area_norms.csv"); ap.add_argument("out", nargs="?", default="config/area_norms.yaml")
    a = ap.parse_args()
    d = convert(a.csv)
    with open(a.out, "w") as f:
        f.write("# Generated by tools/norms_to_yaml.py from Saanvi's sheet. Do not edit by hand; edit the sheet.\n")
        yaml.safe_dump(d, f, sort_keys=False, allow_unicode=True)
    print(f"wrote {len(d['norms'])} norms to {a.out} (skipped {d['skipped_rows']} rows not checked = ok)")
